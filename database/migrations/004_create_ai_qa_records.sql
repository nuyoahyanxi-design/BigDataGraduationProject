CREATE TABLE ai_qa_records (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 request_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 mode VARCHAR(20) NOT NULL,
 resource_id BIGINT UNSIGNED NULL,
 resource_version INT UNSIGNED NULL,
 request_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 question TEXT NOT NULL,
 answer MEDIUMTEXT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 provider VARCHAR(30) NOT NULL,
 model VARCHAR(100) NOT NULL,
 prompt_version VARCHAR(30) NOT NULL,
 consent_version VARCHAR(30) NOT NULL,
 provider_request_id VARCHAR(200) NULL,
 input_tokens INT UNSIGNED NULL,
 output_tokens INT UNSIGNED NULL,
 latency_ms INT UNSIGNED NULL,
 error_code VARCHAR(50) NULL,
 created_at DATETIME(3) NOT NULL,
 finished_at DATETIME(3) NULL,
 PRIMARY KEY (id),
 UNIQUE KEY uk_ai_qa_request_uuid (request_uuid),
 KEY idx_ai_qa_user_time (user_id,created_at,id),
 KEY idx_ai_qa_status_time (status,created_at),
 KEY fk_ai_qa_resource (resource_id),
 CONSTRAINT fk_ai_qa_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ai_qa_resource FOREIGN KEY (resource_id) REFERENCES resources(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT chk_ai_qa_mode CHECK ((mode='general' AND resource_id IS NULL AND resource_version IS NULL) OR (mode='resource' AND resource_id IS NOT NULL AND resource_version >= 1)),
 CONSTRAINT chk_ai_qa_status CHECK (status IN ('pending','succeeded','failed','unknown')),
 CONSTRAINT chk_ai_qa_answer CHECK (status <> 'succeeded' OR (answer IS NOT NULL AND CHAR_LENGTH(TRIM(answer)) > 0)),
 CONSTRAINT chk_ai_qa_question CHECK (CHAR_LENGTH(TRIM(question)) BETWEEN 1 AND 2000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
